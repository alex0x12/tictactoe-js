import { X, O, idx, inside } from './board.js';

// eval.js оценивает позицию без победителя: насколько она хороша для крестика.
// ИИ зовёт эту оценку, когда дошёл до предела глубины и дальше перебирать не может.
// Модуль не знает о правилах победы и не импортирует rules.js: победу ловит поиск
// раньше, чем дело дойдёт до оценки.

// WIN это оценка победы. Отдельная константа, а не вес окна: она обязана быть больше
// любой суммы эвристики и больше N * N, иначе WIN - ply может уйти в минус.
const WIN = 10_000_000;

// DIRECTIONS это четыре направления окна: горизонталь, вертикаль и две диагонали.
// Те же, что в rules.js, но импортировать их оттуда нельзя: eval.js и rules.js
// друг от друга не зависят.
const DIRECTIONS = [[0, 1], [1, 0], [1, 1], [1, -1]];

// weight(n, K) это вклад живого окна, в котором n камней одного цвета. Вес зависит
// от того, сколько камней не хватает до K: одного, 1000; двух, 100; трёх, 10;
// четырёх и больше, 1. Полное окно (не хватает нуля) даёт 10000, но в поиске его
// не бывает: победу ловят раньше оценки.
// Так сумма по всем окнам всегда меньше WIN при любых N и K, а достроить окно до
// следующей ступени всегда выгодно. При K = 5 это ровно 1, 10, 100, 1000.
function weight(n, K) {
  return 10 ** Math.max(0, 4 - (K - n));
}

// rawScore(cells, N, K) складывает вклад всех окон длины K, всегда с точки зрения крестика.
// Окно с камнями обоих цветов мёртвое и ничего не даёт. Окно только с крестиками
// прибавляет weight(x, K), только с ноликами вычитает weight(o, K).
// r и c это начало окна, dr и dc шаг направления, x и o сколько в окне крестиков
// и ноликов. Окно берём, только если его последняя клетка не вылезла за поле.
function rawScore(cells, N, K) {
  let total = 0;

  for (const [dr, dc] of DIRECTIONS) {
    for (let r = 0; r < N; r++) {
      for (let c = 0; c < N; c++) {
        if (!inside(r + dr * (K - 1), c + dc * (K - 1), N)) continue;

        let x = 0;
        let o = 0;
        for (let k = 0; k < K; k++) {
          const v = cells[idx(r + dr * k, c + dc * k, N)];
          if (v === X) x++;
          else if (v === O) o++;
        }

        if (x > 0 && o > 0) continue;            // мёртвое окно
        if (x > 0) total += weight(x, K);
        else if (o > 0) total -= weight(o, K);
      }
    }
  }

  return total;
}

// evaluate(cells, N, K, player) возвращает оценку с точки зрения player. Для нолика это
// rawScore с обратным знаком. Поиск в форме negamax держится на этом равенстве:
// evaluate(X) === -evaluate(O). Поэтому никаких отдельных множителей на чужие угрозы.
function evaluate(cells, N, K, player) {
  const raw = rawScore(cells, N, K);
  return player === X ? raw : -raw;
}

export { WIN, weight, rawScore, evaluate };
